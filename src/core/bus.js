/**
 * Шина событий — способ модулям общаться, не зная друг о друге.
 *
 * ─── Зачем ──────────────────────────────────────────────────────────────────
 * Когда история (модуль story) доходит до сцены «Разделение», ракета
 * (модуль rocket) должна отстрелить ускорители. Можно было бы импортировать
 * ракету в историю и вызвать метод — но тогда историю нельзя использовать
 * без ракеты, а ракету — без истории. Вместо этого:
 *
 *   story:  ctx.bus.emit('story:scene', 2)        // «случилось вот это»
 *   rocket: ctx.bus.on('story:scene', (i) => …)   // «если случится — сделаю вот так»
 *
 * Модули договариваются только об ИМЕНИ события и данных. Список событий
 * проекта — docs/04-architecture.md.
 *
 * ─── replay: поздние подписчики ───────────────────────────────────────────────
 * Шина помнит последнее значение каждого события. Подписка с
 * `{ replay: true }` сразу получает его. Зачем: ракета загружается позже
 * истории (ждёт three.js), а браузер при перезагрузке может открыть страницу
 * сразу в середине — история уже сообщила «сцена 3», а ракета ещё не слушала.
 * Без replay ракета бы так и осталась с ускорителями.
 *
 * ─── Как перенести ─────────────────────────────────────────────────────────
 * Файл ни от чего не зависит. В React/Vue вместо него можно использовать
 * контекст/стор (Zustand, Pinia), но шина проще и работает где угодно.
 * @module core/bus
 */

export function createBus() {
  /** Подписчики: имя события → набор функций. Set — чтобы одна функция не подписалась дважды. */
  const handlers = new Map()
  /** Последнее значение каждого события — для поздних подписчиков (replay). */
  const last = new Map()

  return {
    /**
     * Подписаться на событие.
     * @param {string} event Имя события.
     * @param {(payload: any) => void} fn Обработчик.
     * @param {{ replay?: boolean }} [options] replay — сразу получить последнее значение, если оно было.
     * @returns {() => void} Функция отписки (обязательно вызвать в destroy модуля).
     */
    on(event, fn, { replay = false } = {}) {
      if (!handlers.has(event)) handlers.set(event, new Set())
      handlers.get(event).add(fn)
      if (replay && last.has(event)) fn(last.get(event))
      return () => handlers.get(event)?.delete(fn)
    },
    /** Последнее отправленное значение события (или undefined, если его не было). */
    last(event) {
      return last.get(event)
    },
    /**
     * Отправить событие всем подписчикам. Ошибка в одном подписчике пишется
     * в консоль и НЕ мешает остальным получить событие.
     */
    emit(event, payload) {
      last.set(event, payload)
      handlers.get(event)?.forEach((fn) => {
        try {
          fn(payload)
        } catch (error) {
          console.error(`bus:${event}`, error)
        }
      })
    },
    /** Снять все подписки и забыть значения (при остановке приложения). */
    clear() {
      handlers.clear()
      last.clear()
    },
  }
}
