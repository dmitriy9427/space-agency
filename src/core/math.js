/**
 * Математические помощники. Чистые функции: не трогают DOM, не зависят от
 * GSAP — поэтому работают где угодно (браузер, Node, React Native) и
 * полностью покрыты тестами (math.test.js — там же примеры использования).
 *
 * Почти все эффекты проекта собраны из этих нескольких функций. Если
 * понять их, остальной код читается гораздо легче.
 * @module core/math
 */

/**
 * Ограничить число диапазоном: меньше min → min, больше max → max.
 * clamp(5, 0, 1) = 1; clamp(-5, 0, 1) = 0; clamp(0.5, 0, 1) = 0.5
 */
export const clamp = (v, min, max) => Math.min(Math.max(v, min), max)

/**
 * Линейная интерполяция: точка на отрезке от a до b.
 * t = 0 → a, t = 1 → b, t = 0.5 → ровно посередине.
 * lerp(10, 20, 0.25) = 12.5
 */
export const lerp = (a, b, t) => a + (b - a) * t

/**
 * Обратная интерполяция: «где v между a и b» (0…1 внутри отрезка).
 * invLerp(10, 20, 12.5) = 0.25. При a === b возвращает 0 (иначе деление на ноль).
 */
export const invLerp = (a, b, v) => (a === b ? 0 : (v - a) / (b - a))

/**
 * Перевести число из одного диапазона в другой.
 * remap(0, 10, 100, 200, 5) = 150 — «5 из 0…10» это «150 из 100…200».
 */
export const remap = (inMin, inMax, outMin, outMax, v) => lerp(outMin, outMax, invLerp(inMin, inMax, v))

/**
 * Сглаженная ступенька: 0 до a, 1 после b, а между ними — плавная
 * S-образная кривая (медленно в начале и в конце). Используется, чтобы
 * переходы не начинались и не заканчивались «рывком» — например, между
 * путевыми точками ракеты.
 */
export const smoothstep = (a, b, v) => {
  const t = clamp(invLerp(a, b, v), 0, 1)

  return t * t * (3 - 2 * t)
}

/**
 * Остаток от деления, всегда неотрицательный.
 * В JavaScript −1 % 5 === −1, а для «кругового» индекса нужно 4:
 * mod(-1, 5) = 4 («на шаг назад от первого слайда — последний»).
 */
export const mod = (n, m) => ((n % m) + m) % m

/**
 * «Завернуть» число в полуинтервал [min, max): что вышло за max, появляется
 * от min, и наоборот. На этом держатся все бесконечные ленты и сетки:
 * карточка ушла за правый край — её позиция заворачивается к левому.
 * wrap(12, 0, 10) = 2; wrap(-3, 0, 10) = 7.
 */
export const wrap = (v, min, max) => mod(v - min, max - min) + min

/**
 * Плавное «догоняние» цели, НЕ зависящее от частоты кадров.
 *
 * Наивное `current += (target - current) * 0.1` на экране 120 Гц догоняет
 * вдвое быстрее, чем на 60 Гц. Эта формула учитывает время кадра dt: два
 * шага по 0.05 с дают ровно то же, что один шаг 0.1 с.
 *
 * @param {number} current Текущее значение.
 * @param {number} target Цель.
 * @param {number} lambda «Жёсткость»: чем больше, тем быстрее догоняет (примерно 1/время).
 * @param {number} dt Время кадра в секундах.
 * Подробно — docs/02-concepts.md, раздел 2.2.
 */
export const damp = (current, target, lambda, dt) => lerp(current, target, 1 - Math.exp(-lambda * dt))

/** Знак числа: −1, 0 или 1. */
export const sign = (v) => (v > 0 ? 1 : v < 0 ? -1 : 0)

/** Градусы → радианы (three.js и Math.sin/cos работают в радианах). */
export const rad = (deg) => (deg * Math.PI) / 180
