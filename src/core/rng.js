/**
 * Генератор псевдослучайных чисел с «зерном» (seed).
 *
 * Math.random() каждый раз даёт новые числа. Иногда нужно наоборот: чтобы
 * «случайность» была ОДИНАКОВОЙ при каждой загрузке — например, звёзды на
 * фоне ракеты должны стоять на тех же местах, а тесты — получать одни и те
 * же значения. Для этого генератор с зерном: одно и то же зерно → одна и та
 * же последовательность чисел.
 *
 * Алгоритм mulberry32 — короткий, быстрый и достаточно «случайный» для
 * графики (для криптографии такие генераторы не годятся).
 *
 *   const rng = createRng(42)
 *   rng()            // 0…1
 *   rng.range(-2, 3) // от −2 до 3
 *   rng.int(1, 6)    // кубик: целое 1…6
 *   rng.pick(['a', 'b'])
 * @module core/rng
 */

/**
 * @param {number} seed Любое целое число.
 */
export function createRng(seed) {
  let s = seed >>> 0 // привести к 32-битному беззнаковому целому

  // Сам алгоритм mulberry32: перемешивание битов. Понимать каждую строку не
  // обязательно — важно, что результат равномерно распределён в [0, 1).
  const next = () => {
    s = (s + 0x6d2b79f5) >>> 0
    let t = s

    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }

  /** Число в [a, b). */
  next.range = (a, b) => a + (b - a) * next()
  /** Целое в [a, b] включительно. */
  next.int = (a, b) => Math.floor(next.range(a, b + 1))
  /** Случайный элемент массива. */
  next.pick = (list) => list[Math.floor(next() * list.length)]
  /** true с вероятностью p (0…1). */
  next.chance = (p) => next() < p

  return next
}
