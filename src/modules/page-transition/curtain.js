/**
 * Логика «занавеса» между страницами — без WebGL (тестируется отдельно).
 *
 * ─── Одна шкала на весь переход ─────────────────────────────────────────────
 * Прогресс перехода `t` идёт от 0 до 2:
 *
 *   t = 0 … 1  — «закрытие»: занавес поднимается снизу и закрывает экран;
 *   t = 1      — экран закрыт целиком → в этот момент подменяем страницу;
 *   t = 1 … 2  — «открытие»: занавес продолжает движение вверх и уходит,
 *                открывая новую страницу.
 *
 * Занавес не «откатывается» назад, а проходит насквозь — поэтому переход
 * выглядит как одно непрерывное движение, а не «закрыли–открыли».
 *
 * Шейдер (transition.glsl.js) получает две границы и закрашивает всё, что
 * между ними: нижняя граница едет первой (закрытие), верхняя — второй.
 * @module page-transition/curtain
 */
import { clamp } from '../../core/math.js'

/** Насколько граница выходит за край кадра в начале и в конце (чтобы рваный край целиком уходил за экран). */
export const OVERSHOOT = 0.15

/**
 * Две границы занавеса в координатах экрана снизу вверх (0 — низ, 1 — верх).
 * Закрашено всё, что МЕЖДУ `bottom` и `top`.
 *
 * @param {number} t Прогресс 0…2.
 * @returns {{ top: number, bottom: number }}
 */
export function curtainEdges(t) {
  const span = 1 + OVERSHOOT * 2
  // Верхний край занавеса поднимается в первой половине…
  const top = clamp(t, 0, 1) * span - OVERSHOOT
  // …нижний край догоняет его во второй.
  const bottom = clamp(t - 1, 0, 1) * span - OVERSHOOT

  return { top, bottom }
}

/**
 * Прогресс для DOM-запасного варианта (без WebGL): непрозрачность чёрного
 * слоя — 0 → 1 при закрытии, 1 → 0 при открытии.
 */
export const fallbackOpacity = (t) => (t <= 1 ? clamp(t, 0, 1) : clamp(2 - t, 0, 1))
